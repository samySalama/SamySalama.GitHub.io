/**
 * يحوّل قائمة لنص مرقّم (للمساعد الذكي).
 * @param {'morning'|'deep'|'general'} type
 * @returns {string}
 */
export function checklistToText(type) {
  const list = checklists[type] ?? checklists.general;
  return `**Checklist ${list.title}:**\n${list.items.map((item, i) => `${i + 1}) ${item}`).join('\n')}`;
}
